package Projects_java.Banking_System.model;

import java.sql.Timestamp;

/**
 * POJO representing a bank account.
 *
 * OOP Concept — Encapsulation: all fields private with controlled access.
 * Business logic (isActive) is kept close to the data it describes.
 */
public class Account {

    private long      accountNumber;
    private String    userEmail;
    private String    fullName;
    private double    balance;
    private String    securityPin;  // stored as SHA-256 hash in DB
    private String    accountType;  // "SAVINGS" or "CURRENT"
    private String    status;       // "ACTIVE" or "FROZEN"
    private Timestamp createdAt;

    /** Default constructor (required for DAO mapping). */
    public Account() {}

    /**
     * Convenience constructor for creating a new account.
     * @param accountNumber generated by AccountDAO
     * @param userEmail     email of the owning user
     * @param fullName      account holder name
     * @param balance       initial deposit amount
     * @param securityPin   plain-text PIN (hashed before storage)
     * @param accountType   "SAVINGS" or "CURRENT"
     */
    public Account(long accountNumber, String userEmail, String fullName,
                   double balance, String securityPin, String accountType) {
        this.accountNumber = accountNumber;
        this.userEmail     = userEmail;
        this.fullName      = fullName;
        this.balance       = balance;
        this.securityPin   = securityPin;
        this.accountType   = accountType;
        this.status        = "ACTIVE";
    }

    // ─── Business Logic ───────────────────────────────────────────────────────

    /** @return true if the account status is ACTIVE (not frozen). */
    public boolean isActive() {
        return "ACTIVE".equalsIgnoreCase(status);
    }

    // ─── Getters ─────────────────────────────────────────────────────────────

    public long      getAccountNumber() { return accountNumber; }
    public String    getUserEmail()     { return userEmail; }
    public String    getFullName()      { return fullName; }
    public double    getBalance()       { return balance; }
    public String    getSecurityPin()   { return securityPin; }
    public String    getAccountType()   { return accountType; }
    public String    getStatus()        { return status; }
    public Timestamp getCreatedAt()     { return createdAt; }

    // ─── Setters ─────────────────────────────────────────────────────────────

    public void setAccountNumber(long accountNumber)   { this.accountNumber = accountNumber; }
    public void setUserEmail(String userEmail)         { this.userEmail     = userEmail; }
    public void setFullName(String fullName)           { this.fullName      = fullName; }
    public void setBalance(double balance)             { this.balance       = balance; }
    public void setSecurityPin(String securityPin)     { this.securityPin   = securityPin; }
    public void setAccountType(String accountType)     { this.accountType   = accountType; }
    public void setStatus(String status)               { this.status        = status; }
    public void setCreatedAt(Timestamp createdAt)      { this.createdAt     = createdAt; }

    @Override
    public String toString() {
        return "Account{number=" + accountNumber + ", name='" + fullName +
               "', balance=" + balance + ", type='" + accountType + "', status='" + status + "'}";
    }
}

